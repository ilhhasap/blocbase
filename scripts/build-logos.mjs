import { existsSync, readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  // AI
  "openai", "claude", "anthropic", "gemini", "mistral", "perplexity", "grok", "xai", "copilot", "midjourney",
  "deepseek", "huggingface", "cursor", "ollama", "qwen", "nvidia",
  // Companies and products
  "google", "apple", "microsoft", "meta", "aws", "github", "gitlab", "vercel", "figma", "framer", "notion", "linear",
  "slack", "discord", "zoom", "telegram", "whatsapp", "messenger", "instagram", "facebook", "x", "tiktok", "youtube",
  "linkedin", "reddit", "pinterest", "snapchat", "threads", "dribbble", "behance", "spotify", "netflix", "twitch",
  "stripe", "paypal", "visa", "mastercard", "applepay", "googlepay", "shopify", "dropbox", "googledrive", "gmail",
  "googlecalendar", "trello", "asana", "jira", "airtable", "supabase", "firebase", "docker", "react", "tailwindcss",
];

const lobe = (name) => `node_modules/@lobehub/icons-static-svg/icons/${name}.svg`;
const simple = (name) => `node_modules/simple-icons/icons/${name}.svg`;
const { default: _unused, ...brands } = await import("simple-icons");
const hexOf = Object.fromEntries(Object.values(brands).map((icon) => [icon.slug, `#${icon.hex}`]));

/** The shapes of a file, or null when it needs something the sanitizer drops (gradients, masks, clips). */
function shapes(file) {
  if (!existsSync(file)) return null;
  const svg = readFileSync(file, "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox || /url\(|<defs|<mask|<clipPath|<linearGradient|<radialGradient|<style/i.test(svg)) return null;
  // A fill rule set on the file's root moves onto each shape, since only the shapes are kept.
  const rule = /<svg[^>]*\sfill-rule="evenodd"/.test(svg);
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return { viewBox, body: rule ? body.replace(/<(path|polygon)(?![^>]*fill-rule)/g, '<$1 fill-rule="evenodd"') : body };
}

const out = {};
const missing = [];
for (const name of NAMES) {
  const color = shapes(lobe(`${name}-color`));
  const mono = shapes(lobe(name)) ?? shapes(simple(name));
  if (!mono) {
    missing.push(name);
    continue;
  }
  const multi = color && /fill="#/.test(color.body) ? color : null;
  const own = color ? /fill="(#[0-9a-fA-F]{3,8})"/.exec(color.body)?.[1] : undefined;
  out[name] = {
    viewBox: mono.viewBox,
    body: mono.body,
    // The colour of the one-colour mark when none is asked for.
    color: hexOf[name] ?? own ?? "#000000",
    ...(multi ? { colored: multi.body, coloredViewBox: multi.viewBox } : {}),
  };
}
// OpenAI's mark is shown in black.
if (out.openai) out.openai.color = "#000000";
writeFileSync(
  "src/lib/mimic-logos.ts",
  "/* eslint-disable */\n// Generated by scripts/build-logos.mjs; do not edit by hand. Logos are trademarks of their owners.\n" +
    `import type { Logo } from "./mimic-icons.ts";\n\nconst logos: Record<string, Logo> = ${JSON.stringify(out)};\n\nexport default logos;\n`,
);
console.log(`${Object.keys(out).length} logos; missing: ${missing.join(", ") || "none"}`);
